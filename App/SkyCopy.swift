    static func text(_ key: Key, values: [String: String] = [:]) -> String {
        do { return try SkyDialogueLibrary.catalog.copyText(key.rawValue, values: values) }
        catch { preconditionFailure("Invalid interface copy \(key.rawValue): \(error)") }
    }

    static func count(_ one: Key, _ many: Key, _ count: Int) -> String {
        count == 1 ? text(one) : text(many, values: ["count": String(count)])
    }

    static func position(row: Int, column: Int) -> String {
        text(.a11yPosition, values: ["row": String(row), "column": String(column)])
    }
